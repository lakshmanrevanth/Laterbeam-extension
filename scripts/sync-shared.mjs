// 1. Writes shared/config.js from .env (or environment variables, e.g. in CI).
// 2. Copies /shared into the extension (Chrome can't load files outside the extension folder).
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

function readEnv(file) {
  if (!existsSync(file)) return {};
  const out = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return out;
}

const env = { ...readEnv('.env'), ...process.env };
const get = (k) => env[`VITE_${k}`] || '';

const config = {
  apiKey: get('FIREBASE_API_KEY'),
  authDomain: get('FIREBASE_AUTH_DOMAIN'),
  projectId: get('FIREBASE_PROJECT_ID'),
  storageBucket: get('FIREBASE_STORAGE_BUCKET'),
  messagingSenderId: get('FIREBASE_MESSAGING_SENDER_ID'),
  appId: get('FIREBASE_APP_ID'),
};
const webAppUrl = get('WEB_APP_URL') || (config.projectId ? `https://${config.projectId}.web.app/` : '');

writeFileSync(
  'shared/config.js',
  `// GENERATED by \`npm run sync\` from .env. Do not edit; edit .env instead.
export const firebaseConfig = ${JSON.stringify(config, null, 2)};

// Where the web app is hosted (the extension's "Open app" link).
export const WEB_APP_URL = ${JSON.stringify(webAppUrl)};

// Optional reCAPTCHA Enterprise site key. When set, the web app turns on Firebase App Check.
export const APP_CHECK_SITE_KEY = ${JSON.stringify(get('APP_CHECK_SITE_KEY'))};

export const isConfigured = () => Boolean(firebaseConfig.apiKey && firebaseConfig.projectId);
`,
);

const dest = 'extension/lib/shared';
mkdirSync(dest, { recursive: true });
cpSync('shared', dest, { recursive: true });
console.log(`config ${config.apiKey ? 'loaded' : 'EMPTY (copy .env.example to .env)'} · synced shared/ → ${dest}/`);
